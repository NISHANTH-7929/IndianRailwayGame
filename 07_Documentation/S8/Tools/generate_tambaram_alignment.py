"""Author a representative, tangent-continuous railway from retained OSM topology.

Offline deterministic source-to-code generation. OSM supplies horizontal alignment,
not operational directions, platform allocation, gradients, cant or surveyed radii.
"""
import hashlib
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
REF = ROOT / '06_Routes/ChennaiEgmoreTambaram/References/OSM'
HEADER = ROOT / '03_UnrealProject/MyProject/Source/MyProject/Simulation/RailTambaramAlignment.generated.h'

def sub(a,b): return (a[0]-b[0],a[1]-b[1])
def add(a,b): return (a[0]+b[0],a[1]+b[1])
def mul(a,s): return (a[0]*s,a[1]*s)
def norm(a): return math.hypot(*a)
def unit(a): return mul(a,1/norm(a))
def cross(a,b): return a[0]*b[1]-a[1]*b[0]
def distance_to_segment(p,a,b):
    d=sub(b,a); t=max(0,min(1,sum(x*y for x,y in zip(sub(p,a),d))/sum(x*x for x in d)))
    return norm(sub(p,add(a,mul(d,t))))
def simplify(points,epsilon=2.0):
    if len(points)<3:return points
    distances=[distance_to_segment(p,points[0],points[-1]) for p in points[1:-1]]
    index=max(range(len(distances)),key=distances.__getitem__)+1
    if distances[index-1]<=epsilon:return [points[0],points[-1]]
    return simplify(points[:index+1],epsilon)[:-1]+simplify(points[index:],epsilon)
def sample(g,s):
    x,y,h,k,length=g
    if abs(k)<1e-12:return (x+s*math.cos(h),y+s*math.sin(h))
    return (x+(math.sin(h+k*s)-math.sin(h))/k,y+(math.cos(h)-math.cos(h+k*s))/k)

def main():
    raw=(REF/'corridor-reference.json').read_bytes()
    source=json.loads(raw); audit=json.loads((REF/'topology-audit.json').read_text())
    assert hashlib.sha256(raw).hexdigest()==audit['sourceSha256']
    candidate=audit['candidatePaths'][0]
    nodes=source['nodes']; origin=nodes[str(candidate['startNode'])]
    def xy(n):
        return (math.radians(n['lon']-origin['lon'])*6371008.8*math.cos(math.radians(origin['lat'])),
                math.radians(n['lat']-origin['lat'])*6371008.8)
    raw_points=[xy(nodes[str(n)]) for n in candidate['nodes']]
    points=simplify(raw_points)
    heading=math.atan2(*sub(points[1],points[0])[::-1])
    def rotate(p):return (p[0]*math.cos(heading)+p[1]*math.sin(heading),-p[0]*math.sin(heading)+p[1]*math.cos(heading))
    points=[rotate(p) for p in points]
    # Flat safety extensions are authored station envelopes, excluded from OSM fit.
    points=[add(points[0],(-300,0))]+points+[add(points[-1],mul(unit(sub(points[-1],points[-2])),300))]
    trims=[0.0]*len(points); turns=[0.0]*len(points)
    for i in range(1,len(points)-1):
        a=unit(sub(points[i],points[i-1])); b=unit(sub(points[i+1],points[i]))
        theta=math.atan2(cross(a,b),sum(x*y for x,y in zip(a,b)));turns[i]=theta
        # Radius chosen from available source segments; no overlapping fillets.
        trims[i]=min(600*math.tan(abs(theta)/2),norm(sub(points[i],points[i-1]))*.44,norm(sub(points[i+1],points[i]))*.44)
    pieces=[]; cursor=points[0]
    for i in range(1,len(points)-1):
        a=unit(sub(points[i],points[i-1])); b=unit(sub(points[i+1],points[i]));d=trims[i];t=turns[i]
        entry=sub(points[i],mul(a,d)); h=math.atan2(a[1],a[0]); line=norm(sub(entry,cursor))
        if line>1e-7:pieces.append((*cursor,h,0.0,line))
        if abs(t)>1e-7 and d>1e-7:
            radius=d/math.tan(abs(t)/2);k=math.copysign(1/radius,t)
            pieces.append((*entry,h,k,abs(t)*radius))
        cursor=add(points[i],mul(b,d))
    d=sub(points[-1],cursor);pieces.append((*cursor,math.atan2(d[1],d[0]),0.0,norm(d)))
    # Merge same-heading consecutive straights (including the prefix).
    merged=[]
    for g in pieces:
        if merged and abs(g[3])<1e-12 and abs(merged[-1][3])<1e-12 and abs(g[2]-merged[-1][2])<1e-8:
            old=merged[-1];merged[-1]=(*old[:4],old[4]+g[4])
        else:merged.append(g)
    pieces=merged
    # Centre X for legacy two-chunk S6 ownership, retaining origin tangent +X.
    shift=(pieces[0][0]+sample(pieces[-1],pieces[-1][4])[0])/2
    pieces=[(x-shift,y,h,k,l) for x,y,h,k,l in pieces]
    cloud=[];chain=0
    for g in pieces:
        for i in range(max(1,math.ceil(g[4]/2))+1):
            s=g[4]*i/max(1,math.ceil(g[4]/2));cloud.append((chain+s,sample(g,s)))
        chain+=g[4]
    refs=['MS','MSC','NBK','MKK','MBM','SP','GDY','STM','PZA','MN','TLM','PV','CMP','TBMS','TBM']
    stations=[]
    for ref in refs:
        station=next(s for s in audit['stations'] if s['tags'].get('ref')==ref and (ref!='STM' or s['tags'].get('name')=='Saint Thomas Mount'))
        p=rotate(xy(station));p=(p[0]-shift,p[1])
        station_distance,nearest=min(cloud,key=lambda item:norm(sub(p,item[1])))
        stations.append(station_distance)
    deviation=max(min(norm(sub((rotate(p)[0]-shift,rotate(p)[1]),q)) for _,q in cloud) for p in raw_points)
    lines=['#pragma once','// Generated by generate_tambaram_alignment.py; do not hand-edit.',
           '// Horizontal source: © OpenStreetMap contributors, ODbL 1.0.',
           '// Representative fillets/parallel tracks; NOT surveyed or operational railway data.',
           '#include <array>','namespace Rail { namespace TambaramAlignment {',
           'struct Piece { double x,y,yaw,curvature,length; };',
           f'inline constexpr std::array<Piece,{len(pieces)}> Pieces{{{{']
    lines += [' {'+', '.join(f'{v:.12f}' for v in g)+'},' for g in pieces]
    lines += ['}};',f'inline constexpr double Length={chain:.12f};',
              'inline constexpr std::array<double,15> Stations{{'+','.join(f'{v:.12f}' for v in stations)+'}};', '}}']
    HEADER.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    report=dict(sourceSha256=hashlib.sha256(raw).hexdigest(),candidateIndex=0,
                sourceStart=candidate['startNode'],sourceEnd=candidate['endNode'],sourceWays=candidate['ways'],
                sourceLength=candidate['lengthMetres'],authoredLength=chain,pieces=len(pieces),
                stationMetres=dict(zip(refs,stations)),maximumSourceNodeDeviationMetres=deviation,
                minimumCurveRadius=min(1/abs(g[3]) for g in pieces if g[3]),
                attribution='© OpenStreetMap contributors',licence='ODbL-1.0',
                limitations=['Endpoint candidate selected for continuous corridor shape, not verified platform assignment or direction.',
                'Source polyline simplified to 2m tolerance, fillets tangent-continuous; radius not a surveyed railway radius.',
                'No source elevations: grade and cant zero. Parallel tracks and station envelopes representative.',
                '300m authored extensions at both endpoints; station POIs projected OFFLINE only; runtime follows graph station.'])
    (REF/'alignment-audit.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
    print(json.dumps({k:v for k,v in report.items() if k!='sourceWays'},indent=2))

if __name__=='__main__':main()
